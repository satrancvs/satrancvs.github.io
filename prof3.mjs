import { chromium } from 'playwright';
const b = await chromium.launch({executablePath:'/opt/pw-browsers/chromium'});
const ctx = await b.newContext({viewport:{width:1280,height:900}});
const p = await ctx.newPage();
const cdp = await ctx.newCDPSession(p);
await cdp.send('Network.enable');
await cdp.send('Network.emulateNetworkConditions',{offline:false,latency:150,downloadThroughput:1.6*1024*1024/8,uploadThroughput:750*1024/8});
await p.goto('http://localhost:4173/'); await p.waitForTimeout(4000);
const t0=Date.now(); const reqs=[];
p.on('response',async r=>{const u=r.url(); if(!u.includes('localhost:4173/assets')&&!u.includes('favicon')) reqs.push([Date.now()-t0,u.replace('http://localhost:4173','').slice(0,90),r.headers()['content-length']||'']);});
await p.locator('.fen-diagram').scrollIntoViewIfNeeded();
const t1=Date.now();
await p.waitForSelector('.fen-diagram .jc-board-wrapper',{timeout:60000}).catch(()=>{});
const tBoard=Date.now()-t0;
await p.waitForFunction(()=>{const imgs=[...document.querySelectorAll('.fen-diagram img')]; return imgs.length>=10 && imgs.every(i=>i.complete&&i.naturalWidth>0);},{timeout:60000}).catch(()=>{});
console.log({tBoard,tPieces:Date.now()-t0});
console.log(reqs.map(r=>r.join(' ')).join('\n'));
await b.close();
