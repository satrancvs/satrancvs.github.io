import { chromium } from 'playwright';
const b = await chromium.launch({executablePath:'/opt/pw-browsers/chromium'});
const ctx = await b.newContext({viewport:{width:1280,height:900}});
const p = await ctx.newPage();
const cdp = await ctx.newCDPSession(p);
await cdp.send('Network.enable');
await cdp.send('Network.emulateNetworkConditions',{offline:false,latency:150,downloadThroughput:1.6*1024*1024/8,uploadThroughput:750*1024/8});
const t0=Date.now(); const reqs=[]; let ext=0;
p.on('response',r=>{const u=r.url(); if(/chesspublica/.test(u)) reqs.push((Date.now()-t0)+' '+u.replace('http://localhost:4173','').slice(0,60)); if(!u.startsWith('http://localhost')&&!u.startsWith('data:')) ext++;});
await p.goto('http://localhost:4173/',{waitUntil:'load'});
console.log('load',Date.now()-t0);
await p.waitForFunction(()=>window.ChessPublica!==undefined,{timeout:30000}).catch(()=>{});
console.log('base ready at',Date.now()-t0);
const y=await p.evaluate(()=>document.querySelector('.fen-diagram').getBoundingClientRect().top+scrollY); console.log('card y',Math.round(y));
await p.waitForTimeout(500);
await p.locator('.fen-diagram').scrollIntoViewIfNeeded();
const t1=Date.now();
await p.waitForSelector('.fen-diagram .fen-shown',{timeout:30000}).catch(()=>console.log('NOT SHOWN'));
console.log('after scroll, board shown in ms',Date.now()-t1,'; external requests',ext);
console.log(reqs.join('\n'));
await b.close();
